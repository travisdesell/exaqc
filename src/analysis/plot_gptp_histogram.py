def plot_boxplot(values, experiments, groups, title):
    pd.set_option("display.max_rows", None)
    pd.set_option("display.max_columns", None)
    pd.set_option("display.max_colwidth", None)

    sns.set_theme(style="ticks", palette="pastel")

    df_dict = {"Test Accuracy (%)": [], "Experiment": [], "Strategy": []}

    for experiment_list, experiment in zip(values, experiments):
        print(f"processing list for {experiment}:")

        for group, value_list in zip(groups, experiment_list):
            print(f"\tprocessing group {group} with value_list: {value_list}")
            for test_acc in value_list:
                df_dict["Test Accuracy (%)"].append(test_acc)
                df_dict["Experiment"].append(experiment)
                df_dict["Strategy"].append(group)

                print(
                    f"\t\t\tadding row -- test acc: {test_acc}, {experiment}, {group}"
                )

    print("df dict:")
    print(df_dict)
    df = pd.DataFrame(df_dict)
    print(df)

    # Draw a nested boxplot to show bills by day and time
    ax = sns.boxplot(
        x="Strategy",
        y="Test Accuracy (%)",
        hue="Experiment",
        palette=["m", "g", "r"],
        data=df,
    )
    sns.despine(offset=0, trim=True)
    ax.set_title(title)
    plt.show()


